const RTL = new Set(["ar", "fa", "he", "ur"]);

export function labelsFor(language: string | undefined): Labels {
  const base = (language ?? "en").split("-")[0].toLowerCase();
  return { ...EN, ...(T[base] ?? {}) };
}

/** English on the server render, then the browser's language once mounted. */
export function useLabels(): Labels {
  const [labels, setLabels] = useState<Labels>(EN);
  useEffect(() => {
    const lang = navigator.language || "en";
    const base = lang.split("-")[0].toLowerCase();
    setLabels(labelsFor(lang));
    if (T[base]) {
      document.documentElement.lang = base;
      document.documentElement.dir = RTL.has(base) ? "rtl" : "ltr";
    }
  }, []);
  return labels;
}
